// Échappe le texte avant de l'afficher (protection XSS)
function e(?string $text): string {
    return htmlspecialchars($text ?? '', ENT_QUOTES, 'UTF-8');
}

// Jeton CSRF : généré une fois par session, placé dans les formulaires
function csrf_token(): string {
    if (empty($_SESSION['csrf'])) {
        $_SESSION['csrf'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf'];
}

function csrf_check(?string $token): bool {
    return !empty($_SESSION['csrf']) && is_string($token)
        && hash_equals($_SESSION['csrf'], $token);
}

function is_logged_in(): bool {
    return isset($_SESSION['user_id']);
}

// À appeler en haut d'une page réservée aux utilisateurs connectés
function require_login(): void {
    if (!is_logged_in()) {
        header('Location: connexion.php');
        exit;
    }
}

