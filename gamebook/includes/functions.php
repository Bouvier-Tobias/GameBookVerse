// Icône d'une boutique ou d'un site : le logo officiel s'il est dans assets/icons/<clé>.svg,
// sinon une icône générique (voir assets/icons/LISEZMOI.txt)
function brand_icon(string $key): string {
    if (preg_match('/^[a-z0-9]+$/', $key) && is_file(dirname(__DIR__) . '/assets/icons/' . $key . '.svg')) {
        $url = 'assets/icons/' . $key . '.svg';
        return '<span class="brand-icon" style="-webkit-mask-image:url(\'' . $url . '\');mask-image:url(\'' . $url . '\')"></span>';
    }

    $generic = [
        'official'  => 'globe',
        'wikipedia' => 'book',
        'fandom'    => 'book',
        'youtube'   => 'play',
        'twitch'    => 'play',
        'reddit'    => 'message',
        'discord'   => 'message',
        'facebook'  => 'message',
        'twitter'   => 'message',
        'instagram' => 'message',
        'bluesky'   => 'message',
    ];
    return icon($generic[$key] ?? 'cart');
}
